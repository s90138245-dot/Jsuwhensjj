let currentGrade = "هفتم";
let currentLesson = null;
let currentTab = "gam";
const grid = document.getElementById("lessonsGrid");
const gradeTitle = document.getElementById("gradeTitle");
const lessonTitle = document.getElementById("lessonTitle");
const lessonDesc = document.getElementById("lessonDesc");
const tabContent = document.getElementById("tabContent");
const searchInput = document.getElementById("searchInput");
document.querySelectorAll(".grade-btn").forEach(b => b.addEventListener("click", () => { document.querySelectorAll(".grade-btn").forEach(x => x.classList.remove("active")); b.classList.add("active"); currentGrade = b.dataset.grade; currentLesson = null; searchInput.value = ""; render(); }));
document.querySelectorAll(".tab").forEach(t => t.addEventListener("click", () => { document.querySelectorAll(".tab").forEach(x => x.classList.remove("active")); t.classList.add("active"); currentTab = t.dataset.tab; renderContent(); }));
searchInput.addEventListener("input", render);
document.getElementById("printBtn").addEventListener("click", () => window.print());
function render() {
gradeTitle.textContent = "درس‌های پایه " + currentGrade;
const q = searchInput.value.trim();
const lessons = Object.keys(DATA[currentGrade]).filter(n => !q || n.includes(q));
grid.innerHTML = "";
lessons.forEach(name => {
const d = document.createElement("div");
d.className = "card" + (currentLesson === name ? " active" : "");
d.innerHTML = "<h3>" + name + "</h3><p>" + DATA[currentGrade][name].desc + "</p>";
d.onclick = () => { currentLesson = name; render(); };
grid.appendChild(d);
});
renderContent();
}
function renderContent() {
if (!currentLesson) { lessonTitle.textContent = "یک درس را انتخاب کن"; lessonDesc.textContent = "برای دیدن گام‌به‌گام، سوالات متن و نمونه سوال، روی یکی از کارت‌های بالا بزن."; tabContent.innerHTML = "<p>هنوز درسی انتخاب نشده. مثلا در پایه هفتم روی ریاضی بزن تا محتوای کامل ببینی.</p>"; return; }
const data = DATA[currentGrade][currentLesson];
lessonTitle.textContent = currentLesson + " پایه " + currentGrade;
lessonDesc.textContent = data.desc;
if (currentTab === "gam") {
tabContent.innerHTML = data.gam.map((s,i) => "<div class='step'><strong>قدم " + (i+1) + ":</strong> " + s + "</div>").join("");
} else if (currentTab === "matn") {
tabContent.innerHTML = data.matn.map(x => "<div class='q'><strong>سوال: " + x.q + "</strong><div class='a'>پاسخ: " + x.a + "</div></div>").join("");
} else {
tabContent.innerHTML = data.exam.map(x => "<div class='q'><strong>" + x.q + "</strong><div class='a'>پاسخ: " + x.a + "</div></div>").join("") + "<p style='margin-top:10px;color:#6b7280'>این نمونه سوال برای تمرین نوبت اول و دوم طراحی شده و قابل چاپ است.</p>";
}
}
render();